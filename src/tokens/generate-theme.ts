import { createHash } from "node:crypto";
import type { DtcgGroup } from "./types";
import { buildThemes, type BuiltThemes, type ThemeNode } from "./transform";

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function print(node: ThemeNode, indent: number): string {
  const pad = "  ".repeat(indent);
  if (Array.isArray(node)) return `[${node.join(", ")}]`;
  if (typeof node === "object") {
    const entries = Object.entries(node);
    if (!entries.length) return "{}";
    const lines = entries.map(
      ([k, v]) => `${pad}  ${IDENT.test(k) ? k : JSON.stringify(k)}: ${print(v, indent + 1)},`,
    );
    return `{\n${lines.join("\n")}\n${pad}}`;
  }
  return JSON.stringify(node);
}

export const hashOf = (text: string) =>
  createHash("sha256").update(text).digest("hex").slice(0, 12);

export function renderTokensTs(themes: BuiltThemes, hash: string): string {
  return `/* eslint-disable */
// @generated by rn-agentic-dev (figma-to-tokens). DO NOT EDIT BY HAND.
// Source: design/tokens.json (sha256:${hash})
// Regenerate: npx rn-agentic-dev tokens generate
import type { TextStyle } from 'react-native';

export const lightTheme = ${print(themes.light, 0)} as const;

type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly unknown[]
        ? { -readonly [K in keyof T]: Widen<T[K]> }
        : { -readonly [K in keyof T]: K extends 'fontWeight' ? NonNullable<TextStyle['fontWeight']> : Widen<T[K]> };

/** Shape shared by every theme. A missing/extra key in darkTheme is a compile error. */
export type Theme = Widen<typeof lightTheme>;

${
  themes.hasDark
    ? `export const darkTheme: Theme = ${print(themes.dark, 0)};`
    : `// No dark values found in design/tokens.json; dark mirrors light until a Dark mode exists.\nexport const darkTheme: Theme = lightTheme;`
}

export const themes = { light: lightTheme, dark: darkTheme } as const;
export type ThemeName = keyof typeof themes;
`;
}

/** tokens.json text -> tokens.ts text (pure + deterministic). */
export function generateFromTokensJson(tokensJsonText: string): { ts: string; warnings: string[] } {
  const tree = JSON.parse(tokensJsonText) as DtcgGroup;
  const built = buildThemes(tree);
  return { ts: renderTokensTs(built, hashOf(tokensJsonText)), warnings: built.warnings };
}

/** Written once (never overwritten) next to tokens.ts. */
export const THEME_PROVIDER_TSX = `import React, { createContext, useContext, useMemo, type ReactNode } from 'react';
import { useColorScheme } from 'react-native';
import { themes, type Theme, type ThemeName } from './tokens';

interface ThemeContextValue {
  theme: Theme;
  name: ThemeName;
}

const ThemeContext = createContext<ThemeContextValue>({ theme: themes.light, name: 'light' });

export function ThemeProvider({ children, forcedTheme }: { children: ReactNode; forcedTheme?: ThemeName }) {
  const scheme = useColorScheme();
  const name: ThemeName = forcedTheme ?? (scheme === 'dark' ? 'dark' : 'light');
  const value = useMemo(() => ({ theme: themes[name], name }), [name]);
  return <ThemeContext.Provider value={value}>{children}</ThemeContext.Provider>;
}

/** The only way components should read colors, spacing, radius, typography and shadows. */
export const useTheme = () => useContext(ThemeContext);
`;
